export const MESSAGES: Record<Lang, Record<MessageKey, string>> = { en, zh };

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = MESSAGES[lang] ?? MESSAGES.en;
  const template = dict[key] ?? MESSAGES.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'en';
  const candidates = [navigator.language, ...(navigator.languages ?? [])].filter(Boolean) as string[];
  for (const candidate of candidates) {
    if (candidate.toLowerCase().startsWith('zh')) return 'zh';
  }
  return 'en';
}

